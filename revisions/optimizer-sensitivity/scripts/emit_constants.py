#!/usr/bin/env python3
"""Emit the optimizer-sensitivity result as semantic LaTeX constants.

Follows the paper's convention: no measured value is typed
into ``*.tex`` by hand.  This reads the JSON produced by
``ranking_discordance.py`` and the fixture metadata, and writes
``generated/constants-optimizer-sensitivity.tex``, which the paper inputs; the
top-level ``Makefile`` runs it as part of ``make paper``.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def pct(x: float) -> str:
    return f"{100.0 * x:.1f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--discordance", default=str(ROOT / "generated" / "ranking-discordance.json"))
    ap.add_argument("--fixture-meta", default=str(ROOT / "data" / "isostep-fixture.meta.json"))
    ap.add_argument("--out", default=str(ROOT / "generated" / "constants-optimizer-sensitivity.tex"))
    a = ap.parse_args()

    d = json.loads(Path(a.discordance).read_text())
    meta = json.loads(Path(a.fixture_meta).read_text())
    combo = d["by_channel"]["combo"]
    shape = d["by_channel"]["shape"]
    trade = shape.get("shape_demotion_is_the_combo_trade", {})

    n_pairs = meta.get("n_pairs") or len(meta.get("pairs", []))

    lines = [
        "% Generated by revisions/optimizer-sensitivity/scripts/emit_constants.py",
        f"%   from {Path(a.discordance).name} and {Path(a.fixture_meta).name}",
        "% Do not edit by hand.",
        "%",
        "% The comparator is ROSHAMBO2 with the C1/C2/C3 numerics fixes, so none of",
        "% these numbers is attributable to those defects.",
        "",
        r"\newcommand{\OptSensQueries}{%s}" % combo["n_query"],
        r"\newcommand{\OptSensTopK}{%s}" % combo["k"],
        "",
        "% Combination channel -- the objective both engines optimize.",
        r"\newcommand{\OptSensComboTopKOverlapPct}{%s}" % pct(combo["stayed"] / (combo["stayed"] + combo["left"])),
        r"\newcommand{\OptSensShapeTopKOverlapPct}{%s}" % pct(shape["stayed"] / (shape["stayed"] + shape["left"])),
        r"\newcommand{\OptSensComboStayed}{%s}" % f"{combo['stayed']:,}",
        r"\newcommand{\OptSensComboLeft}{%s}" % f"{combo['left']:,}",
        r"\newcommand{\OptSensComboDisplacedPct}{%s}" % pct(combo["frac_displaced"]),
        r"\newcommand{\OptSensComboDemotedPct}{%s}" % pct(combo["frac_demoted"]),
        r"\newcommand{\OptSensComboCensoredPct}{%s}" % pct(combo["frac_censored"]),
        r"\newcommand{\OptSensComboMeanDropWhenDemoted}{%.4f}" % combo["mean_drop_when_demoted"],
        r"\newcommand{\OptSensComboMeanGainWhenDisplaced}{%.4f}" % combo["mean_gain_when_displaced"],
        r"\newcommand{\OptSensComboMeanGainOnPromoted}{%.4f}" % combo["mean_gain_on_promoted"],
        "",
        "% Shape channel read in isolation -- inverts, and the trade below is why.",
        r"\newcommand{\OptSensShapeDemotedPct}{%s}" % pct(shape["frac_demoted"]),
        r"\newcommand{\OptSensShapeDisplacedPct}{%s}" % pct(shape["frac_displaced"]),
    ]
    if trade:
        lines += [
            "",
            "% Of the shape-demoted molecules that have a combination score in both",
            "% engines' top-1000, the fraction scoring HIGHER on combination under",
            "% ROSHAMBO3, and the two means that offset each other.",
            r"\newcommand{\OptSensTradeN}{%s}" % f"{trade['n_with_both_combo_scores']:,}",
            r"\newcommand{\OptSensTradeOfN}{%s}" % f"{trade['n_total_demoted']:,}",
            r"\newcommand{\OptSensTradeHigherComboPct}{%s}" % pct(trade["frac_with_higher_combo_under_r3"]),
            r"\newcommand{\OptSensTradeMeanShapeDrop}{%.4f}" % trade["mean_shape_drop"],
            r"\newcommand{\OptSensTradeMeanComboGain}{%.4f}" % trade["mean_combo_gain"],
        ]
    lines += [
        "",
        "% The diagnostic fixture itself.",
        r"\newcommand{\OptSensFixturePairs}{%s}" % n_pairs,
        "",
    ]
    atomic_write(Path(a.out), "\n".join(lines))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
